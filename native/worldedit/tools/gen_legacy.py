#!/usr/bin/env python3
"""Generate `legacy_ids.rs`: the 1.12 to 1.13 block table for `.schematic` files.

MCEdit and old WorldEdit `.schematic` files store `blockId << 4 | data`, not
block names. Horizon carries the game's own `BlockStateData` table in
`crates/horizon-world/src/datafix/block_state_data.txt`, but that module is
private to the crate, so this copies the mapping into the bundle as a lookup
table.

    python3 gen_legacy.py path/to/horizon/crates/horizon-world/src/datafix/block_state_data.txt

Horizon's table only changes with a new game version, so the output is
committed next to the bundle.
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "legacy_ids.rs"

HEADER = """// Generated by gen_legacy.py from Horizon's
// `crates/horizon-world/src/datafix/block_state_data.txt`. Do not edit.
//
// One line per 1.12 block state: `id`, the block it became in 1.13, and its
// properties (`key=value;...`, empty when the block has none). `id` is
// `blockId << 4 | data`, as `.schematic` files store it.
"""


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    states = {}
    defaults = {}
    for line in pathlib.Path(sys.argv[1]).read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        identifier = int(fields[0])
        name = fields[1]
        properties = fields[2] if len(fields) > 2 else ""
        states[identifier] = (name, properties)
        defaults.setdefault(identifier >> 4, (name, properties))
    rows = []
    for identifier in range(4096):
        name, properties = states.get(
            identifier, defaults.get(identifier >> 4, ("minecraft:air", ""))
        )
        rows.append(f"{identifier}\t{name}\t{properties}")
    text = HEADER + 'pub(super) const LEGACY: &str = "' + "\n".join(rows) + '";\n'
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{OUT.name}: {len(rows)} states, {len(text) // 1024} KiB")


if __name__ == "__main__":
    main()
